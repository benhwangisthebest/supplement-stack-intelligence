#!/usr/bin/env node
// bundle-sizes — per-route first-load JS, derived from the build's own manifest.
// Phase 3 U8 landing (a). Register: docs/01-plan/phase-3-evidence-grounding.plan.md
// §4 U8; cycle artifact docs/01-plan/features/p3-u8-bundle-budget.plan.md.
//
// WHAT IT COMPUTES, and why it is Next's number rather than an approximation.
// `next build` prints "First Load JS" from `computeFromManifest` and
// `getJsPageSizeInKb` in node_modules/next/dist/build/utils.js (Next 15.1.3):
//
//   * first load of a route = sum of the gzip sizes (level 9) of every `.js`
//     file `.next/app-build-manifest.json` lists for that route's `page` entry;
//   * "shared by all"       = the files present under EVERY key of that
//     manifest (pages, layouts and route handlers alike), summed the same way;
//   * "size"                = the route's files that no other key lists.
//
// This file re-implements exactly that, in bytes instead of pretty-printed kB,
// so the figures can be compared at byte precision and cross-checked against
// the table the build prints. It reads the manifest, never stdout: scraping
// console output would bind the budget to a format Next is free to change.
//
// WHAT IT DOES NOT MEASURE. CSS, RSC payloads, route handlers (which ship no
// client JS), and anything loaded after first paint. Gzip bytes also depend on
// the zlib the measuring Node was built with, which is why the baseline records
// it: two machines with different zlib builds can disagree by a few bytes on
// identical chunks. The headroom in verify-bundle.mjs has to absorb that.
//
// USAGE
//   node scripts/bundle-sizes.mjs          print the figures (reads .next)
//   npm run bundle:baseline                rewrite the committed baseline
//
// Rewriting the baseline is only ever this explicit command. `verify:bundle`
// reads the baseline and never writes it, so a budget change is always a diff
// a reviewer sees.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { gzipSync } from "node:zlib";
import { fileURLToPath } from "node:url";

export const DIST_DIR = ".next";
export const BASELINE_PATH = "docs/05-qa/bundle-baseline.json";

/** Next's own normalisation (shared/lib/router/utils/app-paths.js). */
export function normalizeAppPath(key) {
  const segments = key.split("/");
  let out = "";
  segments.forEach((segment, i) => {
    if (!segment) return;
    if (segment.startsWith("(") && segment.endsWith(")")) return;
    if (segment.startsWith("@")) return;
    if ((segment === "page" || segment === "route") && i === segments.length - 1) return;
    out += `/${segment}`;
  });
  return out || "/";
}

/**
 * Per-route first-load JS for the build in `distDir`, in gzip bytes.
 * Throws if there is no build: a missing build must fail, never measure zero.
 */
export function deriveBundleSizes(distDir = DIST_DIR) {
  let manifest;
  try {
    manifest = JSON.parse(readFileSync(join(distDir, "app-build-manifest.json"), "utf8"));
  } catch {
    throw new Error(
      `${distDir}/app-build-manifest.json not found. Run \`npm run build\` first; this ` +
        "script reads the last build and deliberately does not build for you.",
    );
  }
  const pages = manifest.pages ?? {};
  const keys = Object.keys(pages);
  if (keys.length === 0) throw new Error("app-build-manifest.json lists no entries.");

  // How many manifest keys list each file (Next's countBuildFiles).
  const count = new Map();
  for (const key of keys) for (const f of pages[key]) count.set(f, (count.get(f) ?? 0) + 1);

  const gzipCache = new Map();
  const gzip = (file) => {
    if (!gzipCache.has(file)) {
      gzipCache.set(file, gzipSync(readFileSync(join(distDir, file)), { level: 9 }).length);
    }
    return gzipCache.get(file);
  };
  const isJs = (f) => f.endsWith(".js");
  const sum = (files) => files.reduce((n, f) => n + gzip(f), 0);

  const shared = [...count.keys()].filter((f) => count.get(f) === keys.length && isJs(f));
  const sharedSet = new Set(shared);

  const routes = {};
  for (const key of keys.filter((k) => k.endsWith("/page")).sort()) {
    const files = [...new Set(pages[key].filter(isJs))];
    const own = files.filter((f) => count.get(f) === 1 && !sharedSet.has(f));
    routes[normalizeAppPath(key)] = { firstLoadJs: sum(files), size: sum(own) };
  }
  const sorted = Object.fromEntries(Object.entries(routes).sort(([a], [b]) => a.localeCompare(b)));
  return { sharedByAll: sum(shared), routes: sorted };
}

/** The committed baseline: figures plus the zlib that produced them. Nothing path- or time-dependent. */
export function baselineDocument(sizes) {
  return {
    $comment:
      "Generated by `npm run bundle:baseline` (scripts/bundle-sizes.mjs). Do not hand-edit. " +
      "Gzip bytes, level 9, Next 15's First Load JS definition.",
    measuredWith: { zlib: process.versions.zlib },
    sharedByAll: sizes.sharedByAll,
    routes: sizes.routes,
  };
}

/** Next's pretty-bytes style (1000-based, 3 significant digits), for eyeballing against its table. */
export function kB(bytes) {
  return bytes < 1000 ? `${bytes} B` : `${Number((bytes / 1000).toPrecision(3))} kB`;
}

function main() {
  const sizes = deriveBundleSizes();
  if (process.argv.includes("--write")) {
    writeFileSync(BASELINE_PATH, `${JSON.stringify(baselineDocument(sizes), null, 2)}\n`);
    console.log(`bundle-sizes — wrote ${BASELINE_PATH}. Review the diff; it is the budget change.`);
  }
  for (const [route, r] of Object.entries(sizes.routes)) {
    console.log(`${route.padEnd(26)} ${String(r.size).padStart(7)} ${String(r.firstLoadJs).padStart(8)}   (${kB(r.size)} · ${kB(r.firstLoadJs)})`);
  }
  console.log(`${"shared by all".padEnd(26)} ${"".padStart(7)} ${String(sizes.sharedByAll).padStart(8)}   (${kB(sizes.sharedByAll)})`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    main();
  } catch (err) {
    console.error(`bundle-sizes — ${err.message}`);
    process.exit(1);
  }
}
